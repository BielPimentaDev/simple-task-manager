const HEX_RE = /^#([0-9a-f]{3}|[0-9a-f]{6})$/i
const RGB_RE = /^rgb\(\s*(\d+)\s*,\s*(\d+)\s*,\s*(\d+)\s*\)$/

function isInRange(value: number): boolean {
  return Number.isInteger(value) && value >= 0 && value <= 255
}

export function isValidCssColor(value: string): boolean {
  if (!value) return false

  if (CSS_NAMED_COLORS.has(value.toLowerCase())) return true

  if (HEX_RE.test(value)) return true

  const rgbMatch = RGB_RE.exec(value)
  if (rgbMatch) {
    const r = Number(rgbMatch[1])
    const g = Number(rgbMatch[2])
    const b = Number(rgbMatch[3])
    return isInRange(r) && isInRange(g) && isInRange(b)
  }

  return false
}
